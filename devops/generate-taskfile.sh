#!/usr/bin/env bash
# Generates Taskfile.generated.yml with concrete per-item tasks (e.g. jellyfin-up)
# so they show up in `task --list-all` and shell autocompletion.
# Re-run (`task generate`) after changing the service or network lists in Taskfile.yml or the volumes in the compose files.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_file="$root/Taskfile.yml"
output_file="$root/Taskfile.generated.yml"

# Print the (possibly folded multi-line) value of a top-level var from Taskfile.yml.
get_var() {
  awk -v key="  $1:" '
    index($0, key) == 1 { sub(key, ""); sub(/^ *>-?/, ""); printf "%s ", $0; found = 1; next }
    found && /^    / { printf "%s ", $0; next }
    found { exit }
  ' "$source_file"
}

services="$(get_var ADMIN_SERVICES) $(get_var MEDIA_SERVICES) $(get_var TORRENT_SERVICES) $(get_var VPN_SERVICES) $(get_var FINANCE_SERVICES) $(get_var UTIL_SERVICES) $(get_var OTHER_SERVICES)"
networks="$(get_var NETWORKS)"
volumes="$("$root/devops/list-volumes.sh")"

emit() { # name desc target var value
  printf "  %s:\n    desc: %s\n    cmds:\n      - {task: %s, vars: {%s: '%s'}}\n" "$1" "$2" "$3" "$4" "$5"
}

{
  echo "# Generated by devops/generate-taskfile.sh - do not edit by hand."
  echo "version: '3'"
  echo
  echo "tasks:"
  for s in $services; do
    emit "$s-up" "Start $s" up c "$s"
    emit "$s-down" "Stop $s" down c "$s"
    emit "$s-pull" "Pull $s image" pull c "$s"
    emit "$s-log" "Show $s logs" logs c "$s"
    emit "$s-status" "Show $s status" status c "$s"
    emit "$s-restart" "Restart $s" restart c "$s"
    emit "$s-update-and-restart" "Pull and restart $s" update-and-restart c "$s"
    [ "$s" = portainer ] || emit "$s-debug" "Shell into $s" debug c "$s"
  done
  for v in $volumes; do
    emit "$v-create" "Create volume $v" volume-create v "$v"
    emit "$v-remove" "Remove volume $v" volume-remove v "$v"
    emit "$v-inspect" "Inspect volume $v" volume-inspect v "$v"
    emit "$v-backup" "Backup volume $v" volume-backup v "$v"
    emit "$v-backup-and-tar" "Backup and tar volume $v" volume-backup-and-tar v "$v"
  done
  for n in $networks; do
    emit "$n-create" "Create network $n" network-create n "$n"
    emit "$n-remove" "Remove network $n" network-remove n "$n"
    emit "$n-debug" "Shell into ubuntu container on network $n" debug-network n "$n"
  done
} > "$output_file"
